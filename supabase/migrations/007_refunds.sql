-- Refunds (Express Invoice's "Refunds and Returns").
--
-- A refund records money paid back to a customer, usually against an
-- invoice. It works like a credit note plus a payment going out:
--   * the invoice's refunded amount goes up, but its balance doesn't change
--     (the customer doesn't owe anything again);
--   * the GST portion of the refund reduces GST collected in the month of the
--     refund, and the rest reduces sales;
--   * money received in the reports is shown net of refunds.
-- Refunds on voided invoices still count as money paid out, but don't adjust
-- sales or GST (a voided invoice is already excluded from those).

create table if not exists invoice_refunds (
  id uuid primary key default gen_random_uuid(),
  refund_number int generated by default as identity unique,
  invoice_id uuid references invoices(id) on delete set null,
  payment_id uuid references invoice_payments(id) on delete set null,
  customer_id uuid references customers(id) on delete restrict,
  refund_date date not null default current_date,
  method text not null default 'Interac e-Transfer',
  amount numeric(12,2) not null check (amount > 0),   -- total paid back, GST included
  gst_amount numeric(12,2) not null default 0 check (gst_amount >= 0),
  reason text,
  emailed_at timestamptz,
  created_at timestamptz not null default now(),
  check (gst_amount <= amount)
);
create index if not exists invoice_refunds_date_idx on invoice_refunds (refund_date);
create index if not exists invoice_refunds_invoice_idx on invoice_refunds (invoice_id);

alter table invoice_refunds enable row level security;
drop policy if exists "invoice_refunds admin only" on invoice_refunds;
create policy "invoice_refunds admin only" on invoice_refunds for all using (is_admin()) with check (is_admin());

-- A refund can't be more than what's been paid on that invoice (minus earlier refunds).
create or replace function check_refund_amount()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  paid numeric;
  refunded numeric;
begin
  if new.invoice_id is null then
    return new;
  end if;
  select coalesce(sum(amount), 0) into paid from invoice_payments where invoice_id = new.invoice_id;
  select coalesce(sum(amount), 0) into refunded from invoice_refunds where invoice_id = new.invoice_id and id <> new.id;
  if new.amount > paid - refunded + 0.005 then
    raise exception 'Refund of % is more than the % that can still be refunded on this invoice', new.amount, paid - refunded;
  end if;
  return new;
end $$;
revoke execute on function check_refund_amount() from public, anon, authenticated;

drop trigger if exists invoice_refunds_check on invoice_refunds;
create trigger invoice_refunds_check before insert or update on invoice_refunds
  for each row execute function check_refund_amount();

-- And the reverse: a payment can't be deleted or lowered below what has
-- already been refunded on its invoice.
create or replace function check_payment_covers_refunds()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  inv uuid := old.invoice_id;
  paid numeric;
  refunded numeric;
begin
  if inv is null then
    return coalesce(new, old);
  end if;
  select coalesce(sum(amount), 0) into refunded from invoice_refunds where invoice_id = inv;
  if refunded = 0 then
    return coalesce(new, old);
  end if;
  select coalesce(sum(amount), 0) into paid from invoice_payments where invoice_id = inv and id <> old.id;
  if tg_op = 'UPDATE' and new.invoice_id = inv then
    paid := paid + new.amount;
  end if;
  if paid + 0.005 < refunded then
    raise exception 'This payment has been partly refunded (% refunded). Delete the refund first.', refunded;
  end if;
  return coalesce(new, old);
end $$;
revoke execute on function check_payment_covers_refunds() from public, anon, authenticated;

drop trigger if exists invoice_payments_refund_guard on invoice_payments;
create trigger invoice_payments_refund_guard before update or delete on invoice_payments
  for each row execute function check_payment_covers_refunds();

