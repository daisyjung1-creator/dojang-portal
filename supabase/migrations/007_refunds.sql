-- ── Invoice summary now knows about refunds ────────────────────────────
-- (drop + recreate because the column list changes; dependent views first)
drop view if exists customer_balances;
drop view if exists monthly_sales;
drop view if exists invoice_summary;

create view invoice_summary with (security_invoker = true) as
select
  i.*,
  coalesce(p.paid, 0)::numeric(12,2) as amount_paid,
  greatest(i.total - coalesce(p.paid, 0), 0)::numeric(12,2) as balance,
  coalesce(r.refunded, 0)::numeric(12,2) as amount_refunded,
  case
    when i.voided then 'Void'
    when coalesce(r.refunded, 0) > 0 and coalesce(r.refunded, 0) >= i.total - 0.005 then 'Refunded'
    when coalesce(r.refunded, 0) > 0 then 'Partially Refunded'
    when coalesce(p.paid, 0) >= i.total then 'Paid'
    when coalesce(p.paid, 0) > 0 then 'Partially Paid'
    else 'Not Paid'
  end as status
from invoices i
left join (
  select invoice_id, sum(amount) as paid from invoice_payments
  where invoice_id is not null group by invoice_id
) p on p.invoice_id = i.id
left join (
  select invoice_id, sum(amount) as refunded from invoice_refunds
  where invoice_id is not null group by invoice_id
) r on r.invoice_id = i.id;

create view customer_balances with (security_invoker = true) as
select customer_id,
       count(*) as invoice_count,
       sum(total)::numeric(12,2) as total_invoiced,
       sum(balance)::numeric(12,2) as balance,
       max(invoice_date) as last_invoice_date,
       max(invoice_number) as last_invoice_number,
       min(coalesce(due_date, invoice_date)) filter (where balance > 0) as oldest_due_date
from invoice_summary
where not voided and customer_id is not null
group by customer_id;

create view monthly_sales with (security_invoker = true) as
select to_char(invoice_date, 'YYYY-MM') as month,
       count(*) as invoice_count,
       sum(subtotal)::numeric(12,2) as subtotal,
       sum(gst_amount)::numeric(12,2) as gst,
       sum(total)::numeric(12,2) as total,
       sum(balance)::numeric(12,2) as unpaid
from invoice_summary
where not voided and not is_opening_balance
group by 1;

-- Refunds by the month they were paid back.
--   refunded     = all money paid back (for "received, net of refunds")
--   sales_refund = refunds reducing sales (excl. GST), non-voided invoices only
--   gst_refund   = GST portion reducing GST collected, non-voided invoices only
create or replace view monthly_refunds with (security_invoker = true) as
select to_char(r.refund_date, 'YYYY-MM') as month,
       count(*) as refund_count,
       sum(r.amount)::numeric(12,2) as refunded,
       coalesce(sum(r.amount - r.gst_amount) filter (where not coalesce(i.voided, false)), 0)::numeric(12,2) as sales_refund,
       coalesce(sum(r.gst_amount) filter (where not coalesce(i.voided, false)), 0)::numeric(12,2) as gst_refund
from invoice_refunds r
left join invoices i on i.id = r.invoice_id
group by 1;
